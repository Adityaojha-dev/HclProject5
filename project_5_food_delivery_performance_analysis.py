import pandas as pd

FILE_NAME = "food_orders.csv"


class FoodDeliveryAnalysis:

    def __init__(self, file_name):
        self.data = pd.read_csv(file_name)

    def show_orders(self):
        print("\n--- ALL ORDERS ---")
        print(self.data.to_string(index=False))

    def order_analysis(self):
        total = len(self.data)
        delivered = (self.data["status"] == "Delivered").sum()
        cancelled = (self.data["status"] == "Cancelled").sum()

        completed = self.data[
            self.data["status"] == "Delivered"
        ]

        average_time = completed["delivery_time"].mean()

        delayed = (
            completed["delivery_time"] >
            completed["expected_time"]
        ).sum()

        print("\n--- ORDER PERFORMANCE ---")
        print("Total orders:", total)
        print("Delivered orders:", delivered)
        print("Cancelled orders:", cancelled)
        print("Average delivery time:",
              round(average_time, 2), "minutes")
        print("Delayed deliveries:", delayed)

    def revenue_analysis(self):
        completed = self.data[
            self.data["status"] == "Delivered"
        ]

        revenue = completed["amount"].sum()
        average_order = completed["amount"].mean()

        highest = completed.loc[
            completed["amount"].idxmax()
        ]

        print("\n--- REVENUE ANALYSIS ---")
        print("Total revenue: Rs.", revenue)
        print("Average order value: Rs.",
              round(average_order, 2))
        print("Highest order: Rs.", highest["amount"])
        print("Order ID:", highest["order_id"])

    def restaurant_analysis(self):
        completed = self.data[
            self.data["status"] == "Delivered"
        ]

        orders = completed["restaurant"].value_counts()

        revenue = completed.groupby(
            "restaurant"
        )["amount"].sum()

        print("\n--- RESTAURANT PERFORMANCE ---")
        print("Orders by restaurant:\n", orders)
        print("\nRevenue by restaurant:\n", revenue)
        print("\nTop restaurant:", orders.idxmax())

    def customer_analysis(self):
        completed = self.data[
            self.data["status"] == "Delivered"
        ]

        customer_orders = completed["customer"].value_counts()

        spending = completed.groupby(
            "customer"
        )["amount"].sum()

        print("\n--- CUSTOMER ANALYSIS ---")
        print("Unique customers:",
              self.data["customer"].nunique())
        print("Most orders by:", customer_orders.idxmax())
        print("Highest spending customer:",
              spending.idxmax())
        print("Highest spending: Rs.", spending.max())

    def delivery_analysis(self):
        completed = self.data[
            self.data["status"] == "Delivered"
        ].copy()

        on_time = (
            completed["delivery_time"] <=
            completed["expected_time"]
        ).sum()

        delayed = len(completed) - on_time

        percentage = (on_time / len(completed)) * 100

        partner_time = completed.groupby(
            "partner"
        )["delivery_time"].mean()

        print("\n--- DELIVERY EFFICIENCY ---")
        print("On-time deliveries:", on_time)
        print("Delayed deliveries:", delayed)
        print("On-time percentage:",
              round(percentage, 2), "%")

        print("Average delivery time by partner:\n",
              partner_time.round(2))


def main():

    try:
        analysis = FoodDeliveryAnalysis(FILE_NAME)

        while True:

            print("\n====== FOOD DELIVERY ANALYSIS ======")
            print("1. View all orders")
            print("2. Order performance")
            print("3. Revenue analysis")
            print("4. Restaurant performance")
            print("5. Customer analysis")
            print("6. Delivery efficiency")
            print("7. Exit")

            choice = input("Enter your choice (1-7): ")

            if choice == "1":
                analysis.show_orders()

            elif choice == "2":
                analysis.order_analysis()

            elif choice == "3":
                analysis.revenue_analysis()

            elif choice == "4":
                analysis.restaurant_analysis()

            elif choice == "5":
                analysis.customer_analysis()

            elif choice == "6":
                analysis.delivery_analysis()

            elif choice == "7":
                print("Thank you for using the project!")
                break

            else:
                print("Invalid choice. Try again.")

    except FileNotFoundError:
        print("Dataset not found! Check your CSV file.")


if __name__ == "__main__":
    main()